//! The systemd launcher: a [`Plan`] becomes `qemu-system@<name>.service`,
//! one `virtiofsd@<name>-<tag>.socket` and `.service` per helper, and
//! the symlinks `[Install]` asks for, all in the generator's output
//! directory (`systemd.generator(7)`).

use std::fmt::{self, Write as _};
use std::path::{Path, PathBuf};

use crate::plan::{Helper, Paths, Plan, Tag};
use crate::search::{Scope, Source, UnitName};
use crate::unitfile::UnitFile;

pub const GENERATOR: &str = "qemu-system-generator";

/// The sections copied into the machine's service.
pub const SECTIONS: [&str; 3] = ["Unit", "Service", "Install"];

/// The tools the generated units call; see `build.rs`.
const QMP_POWERDOWN: &str = env!("QMP_POWERDOWN");
const SOCAT: &str = env!("SOCAT");
const VARLINKCTL: &str = env!("VARLINKCTL");
const SSH: &str = env!("SSH");

/// Paths spelled with specifiers (`systemd.unit(5)`): `%t` is the
/// runtime directory root of the manager that loads the unit and `%i`
/// the instance, so one spelling serves both scopes. The machine name
/// is `%i` of the machine's unit, so it is never written out.
pub struct SystemdPaths;

impl Paths for SystemdPaths {
    fn runtime_dir(&self, _machine: &UnitName, program: &str) -> String {
        format!("%t/{program}/%i")
    }

    fn helper_socket(&self, _machine: &UnitName, program: &str, tag: &Tag) -> String {
        helper_socket_path(program, &format!("%i-{tag}"))
    }
}

/// The runtime directory of a helper, relative to `%t`, for its
/// instance `<name>-<tag>`. The machine's unit spells that `%i-<tag>`,
/// the helper's own units `%i`.
fn helper_runtime_dir(program: &str, instance: &str) -> String {
    format!("{program}/{instance}")
}

fn helper_socket_path(program: &str, instance: &str) -> String {
    format!(
        "%t/{}/{program}.sock",
        helper_runtime_dir(program, instance)
    )
}

#[derive(Debug, PartialEq, Eq)]
pub struct GeneratedFile {
    /// Relative to the output directory.
    pub path: PathBuf,
    pub text: String,
}

#[derive(Debug, PartialEq, Eq)]
pub struct Symlink {
    /// Relative to the output directory.
    pub path: PathBuf,
    pub target: PathBuf,
}

#[derive(Debug, PartialEq, Eq)]
pub struct Output {
    pub files: Vec<GeneratedFile>,
    pub links: Vec<Symlink>,
}

impl Output {
    /// Every path the output puts in the directory.
    pub fn paths(&self) -> impl Iterator<Item = &Path> {
        self.files
            .iter()
            .map(|f| f.path.as_path())
            .chain(self.links.iter().map(|l| l.path.as_path()))
    }
}

/// `qemu-system@<name>.service`, the machine's unit.
fn machine_unit(program: &str, name: &UnitName) -> String {
    format!("{program}@{name}.service")
}

/// `virtiofsd@<name>-<tag>`, the instance string of both helper units.
fn helper_stem(name: &UnitName, program: &str, tag: &Tag) -> String {
    format!("{program}@{name}-{tag}")
}

/// Quote one word of a command line the way `systemd.syntax(7)`
/// "Quoting" reads it back: bare when nothing needs escaping, otherwise
/// in double quotes with backslash and double quote escaped. A lone
/// semicolon would separate commands in `ExecStart=`, so it is escaped.
fn quote(word: &str) -> String {
    if word == ";" {
        return "\\;".to_owned();
    }
    let needs_quotes = word.is_empty()
        || word
            .chars()
            .any(|c| c.is_whitespace() || matches!(c, '"' | '\'' | '\\'));
    if !needs_quotes {
        return word.to_owned();
    }
    let mut quoted = String::with_capacity(word.len() + 2);
    quoted.push('"');
    for c in word.chars() {
        match c {
            '\\' => quoted.push_str("\\\\"),
            '"' => quoted.push_str("\\\""),
            c => quoted.push(c),
        }
    }
    quoted.push('"');
    quoted
}

/// A group of words of a command line, each quoted for `ExecStart=`.
fn words<S: AsRef<str>>(group: &[S]) -> String {
    group
        .iter()
        .map(|w| quote(w.as_ref()))
        .collect::<Vec<_>>()
        .join(" ")
}

/// Unit text under construction. Writing to a `String` cannot fail, so
/// the `fmt::Result`s are dropped on purpose.
struct UnitText {
    text: String,
}

impl UnitText {
    fn new(source: &Path) -> Self {
        let mut unit = Self {
            text: format!("# Automatically generated by {GENERATOR}\n"),
        };
        unit.section("Unit");
        unit.line(format_args!("SourcePath={}", source.display()));
        unit
    }

    fn section(&mut self, name: &str) {
        let _ = writeln!(self.text, "\n[{name}]");
    }

    fn line(&mut self, line: impl fmt::Display) {
        let _ = writeln!(self.text, "{line}");
    }

    /// A command line, one word group per continuation line. `prefix`
    /// is the `-` of a command whose failure is tolerated.
    fn exec(
        &mut self,
        key: &str,
        prefix: &str,
        program: &str,
        groups: impl IntoIterator<Item = String>,
    ) {
        let _ = write!(self.text, "{key}={prefix}{}", quote(program));
        for group in groups {
            let _ = write!(self.text, " \\\n    {group}");
        }
        self.text.push('\n');
    }

    fn passthrough(&mut self, file: &UnitFile, section: &str) {
        for entry in file.entries(section) {
            self.line(format_args!("{}={}", entry.key, entry.value));
        }
    }
}

/// The JSON argument of `io.systemd.Machine.Register`. `%i` is expanded
/// by systemd before the command line is split, `${MAINPID}` inside the
/// quoted word at execution time (`systemd.service(5)`, "Command lines").
fn register_json(plan: &Plan) -> String {
    let mut json = format!(
        "{{\"name\":\"%i\",\"class\":\"vm\",\"service\":\"{}\",\"leader\":${{MAINPID}}",
        plan.program
    );
    if let Some(cid) = plan.vsock_cid {
        let _ = write!(json, ",\"vSockCid\":{cid}");
    }
    if let Some(id) = &plan.uuid {
        let _ = write!(json, ",\"id\":\"{id}\"");
    }
    json.push('}');
    json
}

fn machine_service(source: &Source, file: &UnitFile, plan: &Plan, scope: Scope) -> String {
    let name = &source.name;
    let mut unit = UnitText::new(&source.path);
    if file.last("Unit", "Description").is_none() {
        unit.line("Description=QEMU System Virtual Machine %i");
    }
    unit.line("Documentation=man:qemu-system(1) man:systemd.service(5) man:systemd.kill(5)");
    unit.line("PartOf=machines.target");
    unit.line("Before=machines.target");
    if scope == Scope::System {
        unit.line("After=network.target");
    }
    for helper in &plan.helpers {
        let stem = helper_stem(name, helper.program, &helper.tag);
        unit.line(format_args!("Requires={stem}.socket"));
        unit.line(format_args!("After={stem}.socket"));
        unit.line(format_args!("Requires={stem}.service"));
    }
    unit.passthrough(file, "Unit");

    unit.section("Service");
    unit.line("Type=simple");
    let program = plan.program;
    unit.line(format_args!("SyslogIdentifier={program}@%i"));
    unit.line(format_args!("RuntimeDirectory={program}/%i"));
    unit.line(format_args!("StateDirectory={program}/%i"));
    unit.line(format_args!("WorkingDirectory=%S/{program}/%i"));
    unit.exec(
        "ExecStart",
        "",
        &plan.binary,
        plan.args.iter().map(|a| words(a)),
    );
    unit.exec(
        "ExecStartPost",
        "-",
        VARLINKCTL,
        [
            words(&["call"]),
            words(&["%t/systemd/machine/io.systemd.Machine"]),
            words(&["io.systemd.Machine.Register"]),
            words(&[register_json(plan)]),
        ],
    );
    if let Some(ssh) = &plan.ssh_poweroff {
        let groups = [
            words(&["-o", "ConnectTimeout=5"]),
            words(&["-o", "UserKnownHostsFile=/dev/null"]),
            words(&["-o", "StrictHostKeyChecking=no"]),
            words(&["-o", "IdentitiesOnly=yes"]),
            words(&["-i", &ssh.private_key]),
            words(&[format!("root@vsock/{}", ssh.vsock_cid)]),
            words(&["systemctl", "poweroff"]),
        ];
        unit.exec("ExecStop", "-", SSH, groups);
    }
    unit.exec(
        "ExecStop",
        "-",
        SOCAT,
        [
            words(&[format!("OPEN:{QMP_POWERDOWN}!!OPEN:/dev/null,wronly")]),
            words(&[format!("UNIX-CONNECT:{}", plan.control_socket)]),
        ],
    );
    unit.line("KillSignal=SIGCONT");
    unit.line("KillMode=mixed");
    unit.line("TimeoutStopSec=2min");
    unit.line("Slice=machine.slice");
    unit.line("DevicePolicy=closed");
    for device in &plan.device_allow {
        unit.line(format_args!("DeviceAllow={device}"));
    }
    if let Some(mib) = plan.memlock_mib {
        unit.line(format_args!("LimitMEMLOCK={mib}M"));
    }
    unit.passthrough(file, "Service");

    if file.sections_named("Install").next().is_some() {
        unit.section("Install");
        unit.passthrough(file, "Install");
    }
    unit.text
}

fn helper_socket(source: &Source, program: &str) -> String {
    let mut unit = UnitText::new(&source.path);
    unit.line(format_args!("Description={program} socket for %i"));
    unit.section("Socket");
    unit.line(format_args!(
        "ListenStream={}",
        helper_socket_path(program, "%i")
    ));
    unit.line("SocketMode=0660");
    unit.line(format_args!(
        "RuntimeDirectory={}",
        helper_runtime_dir(program, "%i")
    ));
    unit.text
}

fn helper_service(source: &Source, machine: &str, helper: &Helper) -> String {
    let mut unit = UnitText::new(&source.path);
    unit.line(format_args!("Description={} for %i", helper.program));
    unit.line("StopWhenUnneeded=yes");
    unit.line(format_args!("Before={machine}"));
    for mount in &helper.requires_mounts {
        unit.line(format_args!("RequiresMountsFor={mount}"));
    }
    unit.section("Service");
    unit.line("Type=simple");
    unit.exec(
        "ExecStart",
        "",
        &helper.binary,
        helper.args.iter().map(|a| words(a)),
    );
    unit.text
}

/// The unit types systemd knows (`unit_type_table` in `unit-def.c`).
const UNIT_TYPES: [&str; 11] = [
    "service",
    "socket",
    "target",
    "device",
    "mount",
    "automount",
    "swap",
    "timer",
    "path",
    "slice",
    "scope",
];

/// A unit name read as `unit_name_is_valid()` in systemd's
/// `unit-name.c` reads it: its prefix, its instance (empty for a
/// template, `None` for a plain name) and its type.
fn split_unit_name(name: &str) -> Option<(&str, Option<&str>, &str)> {
    let (stem, kind) = name.rsplit_once('.')?;
    let valid = !stem.is_empty()
        && name.len() < 256
        && UNIT_TYPES.contains(&kind)
        && !stem.starts_with('@')
        && stem
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, ':' | '-' | '_' | '.' | '\\' | '@'));
    if !valid {
        return None;
    }
    Some(match stem.split_once('@') {
        Some((prefix, instance)) => (prefix, Some(instance), kind),
        None => (stem, None, kind),
    })
}

/// The symlinks `systemctl enable` would create for `service`, the
/// machine's unit, with relative targets so that the output directory
/// is self-contained. A value that is not a unit name is reported
/// through `warn` and skipped, so that no link lands outside the
/// directory.
fn install_links(
    file: &UnitFile,
    service: &str,
    name: &UnitName,
    mut warn: impl FnMut(String),
) -> Vec<Symlink> {
    let mut links = Vec::new();
    for (section, entry) in file
        .sections_named("Install")
        .flat_map(|s| s.entries.iter().map(move |e| (s, e)))
    {
        let dir = match entry.key.as_str() {
            "WantedBy" => Some("wants"),
            "RequiredBy" => Some("requires"),
            "UpheldBy" => Some("upholds"),
            "Alias" => None,
            _ => continue,
        };
        for value in entry.value.split_whitespace() {
            let parsed = split_unit_name(value);
            match (dir, parsed) {
                (Some(dir), Some(_)) => links.push(Symlink {
                    path: PathBuf::from(format!("{value}.{dir}")).join(service),
                    target: Path::new("..").join(service),
                }),
                // An alias of an instance is an instance of the same
                // name, a template gets it (`systemctl enable`), and a
                // unit cannot alias itself.
                (None, Some((prefix, Some(instance), "service")))
                    if instance.is_empty() || instance == name.as_str() =>
                {
                    let alias = format!("{prefix}@{name}.service");
                    if alias == service {
                        warn(format!(
                            "{}: [Install] Alias={value} is the unit itself, ignoring",
                            section.at(entry.line)
                        ));
                    } else {
                        links.push(Symlink {
                            path: PathBuf::from(alias),
                            target: PathBuf::from(service),
                        });
                    }
                }
                (Some(_), None) => warn(format!(
                    "{}: [Install] {}={value} is not a unit name, ignoring",
                    section.at(entry.line),
                    entry.key
                )),
                (None, _) => warn(format!(
                    "{}: [Install] Alias={value} is neither a service template nor an instance named {name}, ignoring",
                    section.at(entry.line)
                )),
            }
        }
    }
    links
}

pub fn emit(
    source: &Source,
    file: &UnitFile,
    plan: &Plan,
    scope: Scope,
    warn: impl FnMut(String),
) -> Output {
    let service = machine_unit(plan.program, &source.name);
    let mut files = vec![GeneratedFile {
        path: PathBuf::from(&service),
        text: machine_service(source, file, plan, scope),
    }];
    for helper in &plan.helpers {
        let stem = helper_stem(&source.name, helper.program, &helper.tag);
        files.push(GeneratedFile {
            path: PathBuf::from(format!("{stem}.socket")),
            text: helper_socket(source, helper.program),
        });
        files.push(GeneratedFile {
            path: PathBuf::from(format!("{stem}.service")),
            text: helper_service(source, &service, helper),
        });
    }
    Output {
        files,
        links: install_links(file, &service, &source.name, warn),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn plan() -> Plan {
        Plan {
            program: "qemu-system",
            binary: "/usr/bin/qemu-system-x86_64".to_owned(),
            args: vec![
                vec!["-m".to_owned(), "1".to_owned()],
                vec!["-nographic".to_owned()],
            ],
            helpers: Vec::new(),
            device_allow: vec!["/dev/kvm rw"],
            memlock_mib: None,
            vsock_cid: None,
            uuid: None,
            ssh_poweroff: None,
            control_socket: "%t/qemu-system/%i/qmp.sock".to_owned(),
        }
    }

    fn source() -> Source {
        Source {
            name: "vm".parse().unwrap(),
            path: PathBuf::from("/etc/qemu/systemd/vm.qemu"),
            dropins: Vec::new(),
        }
    }

    #[test]
    fn quoting() {
        assert_eq!(quote("plain"), "plain");
        assert_eq!(quote(""), "\"\"");
        assert_eq!(quote("a b"), "\"a b\"");
        assert_eq!(quote("say \"hi\""), "\"say \\\"hi\\\"\"");
        assert_eq!(quote("back\\slash"), "\"back\\\\slash\"");
        assert_eq!(quote(";"), "\\;");
        assert_eq!(quote("%t/x"), "%t/x");
    }

    #[test]
    fn names() {
        let name: UnitName = "vm".parse().unwrap();
        let tag: Tag = "home".parse().unwrap();
        assert_eq!(machine_unit("qemu-system", &name), "qemu-system@vm.service");
        assert_eq!(helper_stem(&name, "virtiofsd", &tag), "virtiofsd@vm-home");
        assert_eq!(
            SystemdPaths.runtime_dir(&name, "qemu-system"),
            "%t/qemu-system/%i"
        );
        assert_eq!(
            SystemdPaths.helper_socket(&name, "virtiofsd", &tag),
            "%t/virtiofsd/%i-home/virtiofsd.sock"
        );
    }

    #[test]
    fn registration_json() {
        let mut p = plan();
        assert_eq!(
            register_json(&p),
            "{\"name\":\"%i\",\"class\":\"vm\",\"service\":\"qemu-system\",\"leader\":${MAINPID}}"
        );
        p.vsock_cid = Some(7);
        p.uuid = Some("u".to_owned());
        assert!(register_json(&p).ends_with(",\"vSockCid\":7,\"id\":\"u\"}"));
    }

    #[test]
    fn exec_lines_quote_and_continue() {
        let mut unit = UnitText::new(Path::new("/x.qemu"));
        unit.section("Service");
        unit.exec(
            "ExecStart",
            "",
            "/bin/q",
            [
                words(&["-append", "a b"]),
                words(&["-S"]),
                words(&["--shared-dir=/srv/my share"]),
            ],
        );
        assert!(unit.text.ends_with(concat!(
            "[Service]\nExecStart=/bin/q \\\n",
            "    -append \"a b\" \\\n",
            "    -S \\\n",
            "    \"--shared-dir=/srv/my share\"\n",
        )));
    }

    #[test]
    fn user_description_replaces_the_default() {
        let file: UnitFile =
            "[Unit]\nDescription=mine\n[Install]\nWantedBy=machines.target\nAlias=vm@.service\n"
                .parse()
                .unwrap();
        let out = emit(&source(), &file, &plan(), Scope::User, |w| panic!("{w}"));
        let text = &out.files[0].text;
        assert!(!text.contains("QEMU System Virtual Machine"));
        assert!(text.contains("\nDescription=mine\n"));
        assert!(!text.contains("After=network.target"));
        assert_eq!(
            out.links,
            [
                Symlink {
                    path: PathBuf::from("machines.target.wants/qemu-system@vm.service"),
                    target: PathBuf::from("../qemu-system@vm.service"),
                },
                Symlink {
                    path: PathBuf::from("vm@vm.service"),
                    target: PathBuf::from("qemu-system@vm.service"),
                },
            ]
        );
    }

    #[test]
    fn system_scope_orders_after_network() {
        let out = emit(
            &source(),
            &UnitFile::default(),
            &plan(),
            Scope::System,
            |w| panic!("{w}"),
        );
        assert!(out.files[0].text.contains("\nAfter=network.target\n"));
        assert_eq!(out.files[0].path, PathBuf::from("qemu-system@vm.service"));
        assert_eq!(out.links, [] as [Symlink; 0]);
    }

    #[test]
    fn install_values_must_be_unit_names() {
        let file: UnitFile = concat!(
            "[Install]\n",
            "WantedBy=a/b.target ../x.target multi-user.target\n",
            "Alias=../../escape.service /x.service vm.service other@vm.service\n",
            "Alias=other@x.service other@vm.socket alias@vm.service\n",
            "Alias=qemu-system@.service qemu-system@vm.service\n",
        )
        .parse()
        .unwrap();
        let mut warnings = Vec::new();
        let name: UnitName = "vm".parse().unwrap();
        let links = install_links(&file, "qemu-system@vm.service", &name, |w| {
            warnings.push(w);
        });
        let paths: Vec<_> = links.iter().map(|l| l.path.to_str().unwrap()).collect();
        assert_eq!(
            paths,
            [
                "multi-user.target.wants/qemu-system@vm.service",
                "other@vm.service",
                "alias@vm.service",
            ]
        );
        assert_eq!(warnings.len(), 9, "{warnings:?}");
        assert!(warnings[7].ends_with("Alias=qemu-system@.service is the unit itself, ignoring"));
    }

    #[test]
    fn unit_names() {
        assert_eq!(
            split_unit_name("machines.target"),
            Some(("machines", None, "target"))
        );
        assert_eq!(
            split_unit_name("a@.service"),
            Some(("a", Some(""), "service"))
        );
        assert_eq!(
            split_unit_name("a@b@c.service"),
            Some(("a", Some("b@c"), "service"))
        );
        for bad in ["", ".service", "a", "a.bogus", "@a.service", "a/b.service"] {
            assert_eq!(split_unit_name(bad), None, "{bad:?}");
        }
    }
}
